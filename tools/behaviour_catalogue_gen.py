"""Regenerate source/behaviour_catalogue.py from the X3D Unified Object Model (X3DUOM).

    python tools/behaviour_catalogue_gen.py X3dUnifiedObjectModel-4.0.xml            # rewrite the file
    python tools/behaviour_catalogue_gen.py X3dUnifiedObjectModel-4.0.xml --check    # exit 1 when the file differs

X3DUOM is the Web3D Consortium's machine-readable model of every X3D node and field
(https://www.web3d.org/specifications/X3dUnifiedObjectModel-4.0.xml). It is the one source that lists inputOnly and
outputOnly fields (set_fraction, value_changed, touchTime ...), which x3d.py's field declarations leave out. The
catalogue is generated, never edited by hand; its header records the sha256 of the model it was made from.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "source" / "behaviour_catalogue.py"

# group -> node types. A behaviour node lives in the graph; a target is scene content the graph drives or listens to.
BEHAVIOUR = {
    "Time": ["TimeSensor"],
    "Interpolators": ["ScalarInterpolator", "PositionInterpolator", "PositionInterpolator2D", "OrientationInterpolator",
                      "ColorInterpolator", "CoordinateInterpolator", "CoordinateInterpolator2D", "NormalInterpolator",
                      "EaseInEaseOut", "SplinePositionInterpolator", "SplinePositionInterpolator2D",
                      "SplineScalarInterpolator", "SquadOrientationInterpolator"],
    "Followers": ["PositionChaser", "PositionChaser2D", "PositionDamper", "PositionDamper2D", "OrientationChaser",
                  "OrientationDamper", "ScalarChaser", "ScalarDamper", "ColorChaser", "ColorDamper",
                  "CoordinateChaser", "CoordinateDamper", "TexCoordChaser2D", "TexCoordDamper2D"],
    "Event utilities": ["BooleanFilter", "BooleanToggle", "BooleanTrigger", "BooleanSequencer", "IntegerSequencer",
                        "IntegerTrigger", "TimeTrigger"],
    "Pointing sensors": ["TouchSensor", "PlaneSensor", "CylinderSensor", "SphereSensor"],
    "Environment sensors": ["ProximitySensor", "VisibilitySensor", "TransformSensor", "LoadSensor"],
    "Key sensors": ["KeySensor", "StringSensor"],
}
TARGETS = ["Transform", "Group", "Switch", "Billboard", "LOD", "Collision", "Anchor", "Inline",
           "Viewpoint", "OrthoViewpoint", "NavigationInfo", "Background", "Fog",
           "PhysicalMaterial", "Material", "UnlitMaterial", "ImageTexture", "MovieTexture", "TextureTransform",
           "PointLight", "DirectionalLight", "SpotLight",
           "Coordinate", "Color", "ColorRGBA", "Normal", "TextureCoordinate", "Text", "Sound", "AudioClip",
           "HAnimHumanoid", "HAnimJoint"]
SKIP_FIELDS = {"DEF", "USE", "IS", "metadata", "class", "id", "style"}


def load(path):
    data = Path(path).read_bytes()
    root = ET.fromstring(data)
    nodes = {node.get("name"): node for node in root.iter("ConcreteNode")}
    return nodes, root.get("version"), hashlib.sha256(data).hexdigest()


def fields_of(nodes, node_type):
    rows = []
    for field in nodes[node_type].find("InterfaceDefinition").findall("field"):
        name = field.get("name")
        if name in SKIP_FIELDS:
            continue
        rows.append((name, field.get("type"), field.get("accessType"), field.get("default")))
    return rows


def render(path):
    nodes, version, digest = load(path)
    out = [
        "# SPDX-FileCopyrightText: 2026 HagopJay",
        "#",
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        '"""Field tables of the behaviour graph\'s nodes. GENERATED by tools/behaviour_catalogue_gen.py; do not edit by hand.',
        "",
        "NODES[node type] = (group, ((field, X3D field type, access type, default), ...)); TARGETS has the same rows for the",
        "scene nodes a ROUTE may start or end at. Access types are X3D's: initializeOnly, inputOnly, outputOnly, inputOutput.",
        'A default of None means the model gives none (events have no default)."""',
        "",
        f'X3DUOM_VERSION = "{version}"',
        f'X3DUOM_SHA256 = "{digest}"',
        "",
        "NODES = {",
    ]
    for group, types in BEHAVIOUR.items():
        for node_type in types:
            out.append(f'    "{node_type}": ("{group}", (')
            for row in fields_of(nodes, node_type):
                out.append(f"        {row!r},")
            out.append("    )),")
    out.append("}")
    out.append("")
    out.append("TARGETS = {")
    for node_type in TARGETS:
        out.append(f'    "{node_type}": (')
        for row in fields_of(nodes, node_type):
            out.append(f"        {row!r},")
        out.append("    ),")
    out.append("}")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    arguments = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(arguments) != 1:
        sys.exit(__doc__)
    text = render(arguments[0])
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.read_text(encoding="utf-8") == text else 1)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text)} bytes)")
