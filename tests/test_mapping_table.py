"""The mapping table v1 is well formed and its two halves agree with each other and with parity.json (plain Python).

    source/mapping/blender_rna.json   the Blender half (checked against the export by tools/io_sync/perturb.py --check)
    mapping/x3d_fields.json           the X3D half (generated by tools/mapping/build_mapping.py; --check in CI)
"""

from __future__ import annotations

import fnmatch
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLENDER = json.loads((ROOT / "source" / "mapping" / "blender_rna.json").read_text())
X3D = json.loads((ROOT / "mapping" / "x3d_fields.json").read_text())
PARITY = json.loads((ROOT / "tools" / "io_sync" / "parity.json").read_text())
sys.path.insert(0, str(ROOT / "source"))
sys.path.insert(0, str(ROOT / "tools" / "io_sync"))

CLASSES = {"carried", "approximated", "clamped", "dropped", "editor_only"}
GRADES = {"Confirmed", "Likely", "Suspected"}
RULE_KINDS = {"neq", "gt", "always"}


class BlenderHalf(unittest.TestCase):
    def test_schema_and_unique_ids(self):
        self.assertEqual(BLENDER["schema"], "x3d-blender-io.mapping-blender/1")
        ids = [row["id"] for row in BLENDER["rows"]]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertGreaterEqual(len(ids), 250)
        for row in BLENDER["rows"]:
            self.assertRegex(row["id"], r"^[a-z.]+:[A-Za-z0-9_ ]+$", row)

    def test_every_row_has_a_class_reason_and_grade(self):
        for row in BLENDER["rows"] + BLENDER["patterns"]:
            self.assertIn(row["class"], CLASSES, row)
            self.assertIn(row["grade"], GRADES, row)
            self.assertTrue(row["reason"].strip(), row)

    def test_every_loss_says_whether_it_gets_a_receipt_entry(self):
        """A dropped, approximated or clamped row either has a receipt rule or says why it has none: no loss is silent."""
        for row in BLENDER["rows"]:
            if row["class"] in ("dropped", "approximated", "clamped"):
                self.assertTrue(row.get("receipt") or row.get("why_no_receipt"), row["id"])
            if row.get("receipt"):
                rule = row["receipt"]
                self.assertIn(rule.get("kind", "neq"), RULE_KINDS, row["id"])
                if rule.get("kind") == "gt":
                    self.assertIsInstance(rule["value"], (int, float))
                if rule.get("when"):
                    self.assertIn("prop", rule["when"])
                    self.assertIsInstance(rule["when"]["in"], list)

    def test_clamped_rows_have_a_limit(self):
        for row in BLENDER["rows"]:
            if row["class"] == "clamped":
                self.assertEqual(row["receipt"]["kind"], "gt", row["id"])

    def test_reported_through_names_a_real_row(self):
        ids = {row["id"] for row in BLENDER["rows"]}
        for row in BLENDER["rows"]:
            why = row.get("why_no_receipt", "")
            if why.startswith("reported through "):
                self.assertIn(why[len("reported through "):], ids, row["id"])

    def test_x3d_targets_name_real_x3d_nodes(self):
        """The Blender half points into the X3D half: every row's x3d target is a node x3d.py declares."""
        nodes = set(X3D["nodes"])
        for row in BLENDER["rows"]:
            target = row.get("x3d")
            if not target:
                continue
            node, _, fields = target.partition(".")
            self.assertIn(node, nodes, row["id"])
            if fields and node in X3D["nodes"]:
                for field in fields.split("/"):
                    self.assertIn(field, X3D["nodes"][node]["fields"], f"{row['id']}: {node}.{field}")

    def test_a_row_under_a_pattern_is_a_deliberate_exception(self):
        """An exact row wins over a pattern (perturb.Mapping); one that a pattern also matches must say something else."""
        same = [row["id"] for row in BLENDER["rows"] for p in BLENDER["patterns"]
                if any(fnmatch.fnmatchcase(row["id"], m) for m in p["match"]) and row["class"] == p["class"]]
        self.assertEqual(same, [])

    def test_the_first_receipt_entry_the_plan_predicted_is_declared(self):
        """v3 plan: "light energy above 1.75 W clamped to intensity 1" on every Blender-made point and spot light."""
        rows = {row["id"]: row for row in BLENDER["rows"]}
        for group in ("light.point", "light.spot"):
            row = rows[f"{group}:energy"]
            self.assertEqual(row["class"], "clamped")
            self.assertEqual(row["receipt"], {"kind": "gt", "value": 1.75, "unless_custom": "x3d_intensity"})


class X3DHalf(unittest.TestCase):
    def test_sized_to_the_standard(self):
        """Every node and field of x3d.py 4.0.65.8 has a row (R6: 49 rows was the size of the code, not the standard)."""
        self.assertEqual(X3D["schema"], "x3d-blender-io.mapping-x3d/1")
        self.assertEqual(X3D["instruments"]["x3d.py"], "4.0.65.8")
        self.assertEqual(X3D["totals"]["nodes"], len(X3D["nodes"]))
        self.assertEqual(X3D["totals"]["fields"], sum(len(n["fields"]) for n in X3D["nodes"].values()))
        self.assertGreaterEqual(len(X3D["nodes"]), 260)

    def test_every_written_node_has_a_parity_row(self):
        for name, row in X3D["nodes"].items():
            if row["export"] == "written":
                self.assertIn(name, PARITY["nodes"], name)
                self.assertNotEqual(row["class"], "undeclared", name)

    def test_field_classes_are_closed(self):
        allowed = {"exact", "equivalent", "lossy", "unmeasured", "default_only", "import_only", "not_supported",
                   "not_applicable"}
        for name, row in X3D["nodes"].items():
            for field, f in row["fields"].items():
                self.assertIn(f["class"], allowed, f"{name}.{field}")
                if f["access"] in ("inputOnly", "outputOnly"):
                    self.assertEqual(f["class"], "not_applicable", f"{name}.{field}")

    def test_no_attribute_outside_the_standard(self):
        self.assertEqual(X3D["attributes_not_in_x3d_py"], [])

    def test_doc_is_generated_from_the_tables(self):
        doc = (ROOT / "docs" / "MAPPING.md").read_text()
        self.assertIn(f"{X3D['totals']['nodes']} nodes and {X3D['totals']['fields']} fields", doc)
        self.assertIn(f"{len(BLENDER['rows'])} rows and {len(BLENDER['patterns'])} pattern rows", doc)


class FieldLevelParity(unittest.TestCase):
    def test_check_parity_fields_flags_an_attribute_with_no_row(self):
        """Planted fault for the field-level check: a file writing PhysicalMaterial@clearcoat (not a written row)."""
        import tempfile

        import check_parity

        with tempfile.TemporaryDirectory() as tmp:
            good = Path(tmp) / "good.x3d"
            good.write_text("<X3D><Scene><Shape><Appearance><PhysicalMaterial baseColor='1 0 0'/></Appearance>"
                            "</Shape></Scene></X3D>")
            bad = Path(tmp) / "bad.x3d"
            bad.write_text("<X3D><Scene><Shape><Appearance><PhysicalMaterial baseColor='1 0 0' occlusionTextureMapping='uv' "
                           "/></Appearance></Shape></Scene></X3D>")
            fields = str(ROOT / "mapping" / "x3d_fields.json")
            self.assertEqual(check_parity.main(["--fields", fields, str(good)]), 0)
            self.assertEqual(check_parity.main(["--fields", fields, str(bad)]), 1)


if __name__ == "__main__":
    unittest.main()
